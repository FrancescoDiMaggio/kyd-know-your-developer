import React from 'react'
import { Alert, Badge, Box, Card, Grid, HStack, List, SimpleGrid, Stack, Table, Text, Wrap } from '@chakra-ui/react'
import { Sparkles } from 'lucide-react'
import { t } from 'sn-translate'
import { fill } from '../utils/i18n'
import type { InsightPoint, InsightSkill, KydInsights } from '../types'
import { SectionCard } from '../components/SectionCard'
import { fmtDateTime } from '../utils/format'
import { OUTCOME_PALETTE, SEVERITY_PALETTE, outcomeLabel, severityLabel } from '../utils/labels'

function skillName(skill: InsightSkill): string {
    switch (skill) {
        case 'behaviour':
            return t('Behaviour Profile')
        case 'delivery':
            return t('Delivery Outcomes')
        case 'risk':
            return t('Risk and Maturity')
    }
}

function Points({ items }: { items: InsightPoint[] }) {
    return (
        <Stack gap="3">
            {items.map((p, i) => (
                <Box key={i} borderLeftWidth="3px" borderColor="border.emphasized" ps="3">
                    <Text fontWeight="medium" textStyle="sm">
                        {p.title}
                    </Text>
                    <Text textStyle="sm" color="fg.muted">
                        {p.detail}
                    </Text>
                </Box>
            ))}
        </Stack>
    )
}

function Score({ value }: { value: number }) {
    const score = Math.max(0, Math.min(5, Math.round(value)))
    return (
        <HStack gap="1" aria-label={fill(t('%1 out of 5'), score)} role="img">
            {[1, 2, 3, 4, 5].map((n) => (
                <Box key={n} w="3" h="3" borderRadius="full" bg={n <= score ? 'brand.solid' : 'bg.emphasized'} />
            ))}
        </HStack>
    )
}

// Lettura testuale prodotta dalle Skill Now Assist (contenuto generato da AI).
export function InsightsReport({ insights }: { insights: KydInsights }) {
    const { behaviour, delivery, risk } = insights
    return (
        <Stack gap="4">
            <HStack gap="2" color="fg.muted" textStyle="xs">
                <Sparkles size={14} aria-hidden />
                <Text>
                    {fill(t('Generated by Now Assist on %1. AI-generated content: verify it against the data before acting on it.'),
                        fmtDateTime(insights.generatedOn),
                    )}
                </Text>
            </HStack>

            {insights.errors.map((e) => (
                <Alert.Root key={e.skill} status="warning">
                    <Alert.Indicator />
                    <Alert.Content>
                        <Alert.Title>{fill(t('The %1 skill did not return a result'), skillName(e.skill))}</Alert.Title>
                        <Alert.Description wordBreak="break-word">{e.message}</Alert.Description>
                    </Alert.Content>
                </Alert.Root>
            ))}

            {(risk?.classification || behaviour) && (
                <Card.Root bg="brand.subtle" variant="subtle">
                    <Card.Body>
                        <Text textStyle="xs" color="brand.fg" fontWeight="semibold" textTransform="uppercase" letterSpacing="wide">
                            {t('Profile')}
                        </Text>
                        <Text textStyle="lg" fontWeight="semibold" mt="1">
                            {risk?.classification || behaviour?.classification}
                        </Text>
                        {behaviour?.summary && (
                            <Text textStyle="sm" mt="2">
                                {behaviour.summary}
                            </Text>
                        )}
                    </Card.Body>
                </Card.Root>
            )}

            {behaviour && (
                <Grid templateColumns={{ base: '1fr', xl: '1fr 1fr' }} gap="4">
                    <SectionCard title={t('Strengths')}>
                        <Points items={behaviour.strengths} />
                    </SectionCard>
                    <SectionCard title={t('Concerns and risk patterns')}>
                        <Points items={behaviour.concerns} />
                    </SectionCard>
                </Grid>
            )}

            {delivery && delivery.streams.length > 0 && (
                <SectionCard title={t('Work streams')} description={fill(t('%1 streams reconstructed from the conversations'), delivery.streams.length)}>
                    <SimpleGrid columns={{ base: 1, lg: 2 }} gap="3">
                        {delivery.streams.map((s, i) => (
                            <Card.Root key={i} variant="outline" size="sm">
                                <Card.Body>
                                    <HStack justify="space-between" align="start" gap="2">
                                        <Text fontWeight="semibold" textStyle="sm">
                                            {s.title}
                                        </Text>
                                        <Badge colorPalette={OUTCOME_PALETTE[s.outcome] || 'gray'} variant="subtle" flexShrink={0}>
                                            {outcomeLabel(s.outcome)}
                                        </Badge>
                                    </HStack>
                                    <Text textStyle="xs" color="fg.muted" mt="1">
                                        {[s.period, s.scope, s.prompts != null ? fill(t('%1 prompts'), s.prompts) : ''].filter(Boolean).join(' · ')}
                                    </Text>
                                    {s.result && (
                                        <Text textStyle="sm" fontWeight="semibold" mt="1">
                                            {s.result}
                                        </Text>
                                    )}
                                    <Text textStyle="sm" mt="2">
                                        {s.summary}
                                    </Text>
                                    {s.artifacts.length > 0 && (
                                        <Wrap gap="1" mt="2">
                                            {s.artifacts.map((a) => (
                                                <Badge key={a} variant="outline" size="sm" maxW="100%" whiteSpace="normal">
                                                    {a}
                                                </Badge>
                                            ))}
                                        </Wrap>
                                    )}
                                </Card.Body>
                            </Card.Root>
                        ))}
                    </SimpleGrid>
                </SectionCard>
            )}

            {delivery && (delivery.outcomes.length > 0 || delivery.failureCauses.length > 0) && (
                <Grid templateColumns={{ base: '1fr', xl: '3fr 2fr' }} gap="4">
                    <SectionCard title={t('Outcomes of the requests')}>
                        <Table.Root size="sm">
                            <Table.Header>
                                <Table.Row>
                                    <Table.ColumnHeader>{t('Goal')}</Table.ColumnHeader>
                                    <Table.ColumnHeader>{t('Outcome')}</Table.ColumnHeader>
                                </Table.Row>
                            </Table.Header>
                            <Table.Body>
                                {delivery.outcomes.map((o, i) => (
                                    <Table.Row key={i}>
                                        <Table.Cell>
                                            <Text fontWeight="medium" textStyle="sm">
                                                {o.goal}
                                            </Text>
                                            <Text textStyle="xs" color="fg.muted">
                                                {o.detail}
                                            </Text>
                                        </Table.Cell>
                                        <Table.Cell verticalAlign="top">
                                            <Badge colorPalette={OUTCOME_PALETTE[o.status] || 'gray'}>{outcomeLabel(o.status)}</Badge>
                                        </Table.Cell>
                                    </Table.Row>
                                ))}
                            </Table.Body>
                        </Table.Root>
                    </SectionCard>
                    <SectionCard title={t('Main causes of failure')}>
                        <Points items={delivery.failureCauses} />
                    </SectionCard>
                </Grid>
            )}

            {risk && (
                <>
                    <SectionCard title={t('Risk observations')}>
                        <Table.Root size="sm">
                            <Table.Header>
                                <Table.Row>
                                    <Table.ColumnHeader>{t('Severity')}</Table.ColumnHeader>
                                    <Table.ColumnHeader>{t('Finding')}</Table.ColumnHeader>
                                    <Table.ColumnHeader>{t('Action')}</Table.ColumnHeader>
                                </Table.Row>
                            </Table.Header>
                            <Table.Body>
                                {risk.risks.map((x, i) => (
                                    <Table.Row key={i}>
                                        <Table.Cell verticalAlign="top">
                                            <Badge colorPalette={SEVERITY_PALETTE[x.severity] || 'gray'} variant="solid">
                                                {severityLabel(x.severity)}
                                            </Badge>
                                        </Table.Cell>
                                        <Table.Cell textStyle="sm">{x.finding}</Table.Cell>
                                        <Table.Cell textStyle="sm" color="fg.muted">
                                            {x.action}
                                        </Table.Cell>
                                    </Table.Row>
                                ))}
                            </Table.Body>
                        </Table.Root>
                    </SectionCard>
                    <Grid templateColumns={{ base: '1fr', xl: '1fr 1fr' }} gap="4">
                        <SectionCard title={t('Maturity profile')} description={t('From 1 (weak) to 5 (excellent)')}>
                            <Stack gap="3">
                                {risk.maturity.map((m) => (
                                    <Box key={m.dimension}>
                                        <HStack justify="space-between" gap="3">
                                            <Text textStyle="sm" fontWeight="medium">
                                                {m.dimension}
                                            </Text>
                                            <Score value={m.score} />
                                        </HStack>
                                        <Text textStyle="xs" color="fg.muted">
                                            {m.rationale}
                                        </Text>
                                    </Box>
                                ))}
                            </Stack>
                        </SectionCard>
                        <SectionCard title={t('Operational recommendations')}>
                            <List.Root as="ol" gap="2" ps="5" textStyle="sm">
                                {risk.recommendations.map((rec, i) => (
                                    <List.Item key={i}>{rec}</List.Item>
                                ))}
                            </List.Root>
                        </SectionCard>
                    </Grid>
                </>
            )}
        </Stack>
    )
}
